  /* 결정적 난수 (같은 화면을 다시 열어도 목록이 흔들리지 않도록) --------- */
  function rnd(seed) {
    var s = seed % 2147483647;
    if (s <= 0) s += 2147483646;
    return function () {
      s = (s * 16807) % 2147483647;
      return (s - 1) / 2147483646;
    };
  }
  function gcd(a, b) { return b ? gcd(b, a % b) : a; }
  function stride(total) {
    var p = Math.floor(total * 0.618) | 0;
    if (p < 2) p = 2;
    while (gcd(p, total) !== 1) p++;
    return p;
  }

  function pad(n) { return n < 10 ? '0' + n : '' + n; }

  var FORMS = [];
  var idSeq = 100000;

  CATS.forEach(function (cat, ci) {
    var seed = SEED[cat.code];
    var B = seed.base.length, M = seed.mod.length, V = seed.vari.length;
    var space = B * M * V;
    var st = stride(space);
    var r = rnd(7919 + ci * 131);

    for (var i = 0; i < cat.n; i++) {
      var k = (i * st) % space;
      var bi = k % B;
      var mi = Math.floor(k / B) % M;
      var vi = Math.floor(k / (B * M)) % V;

      var base = seed.base[bi];
      var mod = seed.mod[mi];
      var vari = seed.vari[vi];
      var title = base + ' (' + mod + ')' + (vari ? ' ' + vari : '');

      var rr = r();
      var office;
      if (cat.code === 'reg' || cat.code === 'creg') office = REGOFF[Math.floor(r() * REGOFF.length)];
      else if (cat.code === 'admin' || cat.code === 'nonc') office = OTHEROFF[Math.floor(r() * OTHEROFF.length)];
      else if (cat.code === 'depo') office = '관할 공탁소';
      else office = COURTS[Math.floor(r() * COURTS.length)];

      var y = 2019 + Math.floor(r() * 8);
      if (y > 2026) y = 2026;
      var mth = 1 + Math.floor(r() * 12);
      var day = 1 + Math.floor(r() * 28);
      if (y === 2026 && mth > 8) mth = 1 + Math.floor(r() * 8);
      if (y === 2026 && mth === 8 && day > 18) day = 1 + (day % 18);

      var files = ['HWP'];
      if (r() < 0.72) files.push('HWPX');
      if (r() < 0.58) files.push('PDF');
      if (r() < 0.18) files.push('DOCX');

      var gr = r();
      var grade = gr < 0.26 ? 0 : (gr < 0.81 ? 1 : 2);

      var dl = Math.floor(Math.pow(r(), 2.6) * 96000) + 96;

      var stg = seed.stage[Math.floor(r() * seed.stage.length)];
      var src = rr < 0.46 ? 0 : (rr < 0.83 ? 1 : 2);

      FORMS.push({
        id: ++idSeq,
        t: title,
        base: base,
        c: cat.code,
        cn: cat.name,
        s: SOURCES[src],
        o: office,
        r: y + '-' + pad(mth) + '-' + pad(day),
        d: dl,
        g: grade,
        f: files,
        l: seed.law[Math.floor(r() * seed.law.length)],
        st: stg,
        pg: 1 + Math.floor(r() * 6)
      });
    }
  });

