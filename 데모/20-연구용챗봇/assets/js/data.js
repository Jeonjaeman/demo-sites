/* ---------- 참가자 로그 (연구자 콘솔용) ---------- */
function mkParticipants() {
  const conds = ['A', 'B', 'C', 'D'];
  const out = [];
  // 블록 무작위화 결과를 재현 — 4명 블록 단위로 4조건이 1회씩
  for (let blk = 0; blk < 12; blk++) {
    const order = [...conds].sort((a, b) => ((blk * 7 + a.charCodeAt(0)) % 5) - ((blk * 7 + b.charCodeAt(0)) % 5));
    order.forEach((c, j) => {
      const i = blk * 4 + j;
      if (i >= 46) return;
      const turns = 4 + ((i * 5) % 15);
      const done = turns >= STUDY.minTurns;
      const dropped = !done && i % 7 === 3;
      out.push({
        pid: `P${String(1001 + i)}`,
        cond: c,
        turns,
        started: `2026-07-${String(20 + (i % 6)).padStart(2, '0')} ${String(9 + (i % 9)).padStart(2, '0')}:${String((i * 13) % 60).padStart(2, '0')}`,
        dur: `${4 + (i % 11)}분 ${(i * 7) % 60}초`,
        tokens: 820 + (i * 137) % 2400,
        status: dropped ? 'drop' : done ? 'done' : 'prog',
      });
    });
  }
  return out;
}
const PARTICIPANTS = mkParticipants();

/* 집단별 집계 */
function condCounts() {
  const c = { A: 0, B: 0, C: 0, D: 0 };
  PARTICIPANTS.filter(p => p.status !== 'drop').forEach(p => c[p.cond]++);
  return c;
}

