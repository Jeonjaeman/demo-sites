function pickTopic(text) {
  for (const [keys, topic] of KEYWORDS) {
    if (keys.some(k => text.includes(k))) return topic;
  }
  return 'default';
}

/* 조건별로 동일 입력에 다른 스타일의 응답을 구성 */
function buildReply(condition, userText) {
  const [empathy, advice, evidence] = REPLY_BANK[pickTopic(userText)];
  switch (condition) {
    case 'A': return advice;
    case 'B': return `${empathy} ${advice}`;
    case 'C': return `${advice} ${evidence}`;
    case 'D': return `${empathy} ${advice} ${evidence}`;
  }
}

