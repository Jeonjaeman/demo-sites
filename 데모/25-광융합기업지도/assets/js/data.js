function mkCompanies(n){
  const out=[];
  for(let i=0;i<n;i++){
    const reg = REGIONS[Math.floor(rnd()*REGIONS.length)];
    const gun = reg.guns[Math.floor(rnd()*reg.guns.length)];
    const sec = SECTORS[Math.floor(rnd()*SECTORS.length)];
    // 지역 블록 안에 흩뿌리기
    const x = reg.x + rnd()*reg.w;
    const y = reg.y + rnd()*reg.h;

    // 기업 규모 — 광융합은 중소기업 비중이 절대적
    const r = rnd();
    const size = r<0.045 ? '대기업' : r<0.20 ? '중견기업' : '중소기업';

    /* ★ 재무 데이터 출처 — 이 데모의 핵심 발견
       금융공공데이터 API는 법인등록번호 기준 조회이고
       재무제표가 공개되는 기업(상장·외부감사 대상)만 값이 있습니다.
       광융합기업 대부분은 비상장 중소기업이라 API로는 비어 있습니다. */
    let finSrc;
    if(size==='대기업') finSrc='api';
    else if(size==='중견기업') finSrc = rnd()<0.72 ? 'api' : 'xls';
    else finSrc = rnd()<0.11 ? 'api' : (rnd()<0.42 ? 'xls' : 'none');

    const base = size==='대기업' ? 3200 : size==='중견기업' ? 620 : 48;
    const rev = finSrc==='none' ? null : Math.round(base*(0.5+rnd()*1.8));
    const band = rev==null ? null : rev<100?REV_BANDS[0] : rev<500?REV_BANDS[1] : rev<1000?REV_BANDS[2] : REV_BANDS[3];

    // 종업원 수 — 국민연금 사업장 데이터 (3인 이상 법인만 공개)
    const empReal = size==='대기업' ? 900+Math.floor(rnd()*2200)
                  : size==='중견기업' ? 120+Math.floor(rnd()*380)
                  : 1+Math.floor(rnd()*72);       // 소규모는 1~2인 사업장도 존재
    const empPub = empReal>=3 ? empReal : null;   // 법인 3인 미만은 국민연금 데이터 미공개

    out.push({
      id:'C'+String(1001+i),
      name: NAME_A[Math.floor(rnd()*NAME_A.length)].toUpperCase()+NAME_B[Math.floor(rnd()*NAME_B.length)],
      sector: sec.id, sido: reg.sido, gun,
      addr: `${reg.sido} ${gun} 첨단과기로 ${10+Math.floor(rnd()*300)}`,
      x:+x.toFixed(2), y:+y.toFixed(2),
      size, rev, band, finSrc,
      emp: empPub,
      ceo: '김○○', founded: 1985+Math.floor(rnd()*38),
      tel: `0${[62,42,31,2,43,54,55,63][REGIONS.indexOf(reg)]}-***-****`,
      desc: `${sec.name} 분야의 핵심 부품과 모듈을 개발·생산합니다.`,
      products: ['광모듈','광학렌즈','계측장비','레이저 모듈','광학필름','센서 패키지'][Math.floor(rnd()*6)],
      fav:false,
    });
  }
  return out;
}
