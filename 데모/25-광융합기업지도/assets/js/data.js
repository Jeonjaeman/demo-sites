function coverage(){
  const t=COMPANIES.length;
  const api=COMPANIES.filter(c=>c.finSrc==='api').length;
  const xls=COMPANIES.filter(c=>c.finSrc==='xls').length;
  const none=COMPANIES.filter(c=>c.finSrc==='none').length;
  const empNa=COMPANIES.filter(c=>c.emp==null).length;
  return {
    total:t, api, xls, none,
    apiPct:+(api/t*100).toFixed(1), xlsPct:+(xls/t*100).toFixed(1), nonePct:+(none/t*100).toFixed(1),
    empNa, empNaPct:+(empNa/t*100).toFixed(1),
    bySize: SIZES.map(s=>{
      const g=COMPANIES.filter(c=>c.size===s);
      return { size:s, n:g.length, api:g.filter(c=>c.finSrc==='api').length,
        pct: g.length? +(g.filter(c=>c.finSrc==='api').length/g.length*100).toFixed(1):0 };
    }),
  };
}

