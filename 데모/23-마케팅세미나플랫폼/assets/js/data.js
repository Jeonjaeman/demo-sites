/* ---------- 회차 데이터 (결정론적 생성) ---------- */
function mulberry32(a){return function(){a|=0;a=a+0x6D2B79F5|0;let t=Math.imul(a^a>>>15,1|a);t=t+Math.imul(t^t>>>7,61|t)^t;return((t^t>>>14)>>>0)/4294967296}}
const rnd = mulberry32(20260731);

function mkSessions(){
  const out=[];
  ALL_REGIONS.forEach((region,i)=>{
    const grp = Object.keys(REGION_GROUPS).find(g=>REGION_GROUPS[g].includes(region));
    const day = 8 + (i*3) % 50;
    const d = new Date(2026, 7, day);           // 2026-08-08 ~
    const booked = Math.min(BRAND.capacity, Math.floor(rnd()*66));
    const pending = booked >= BRAND.capacity ? 0 : Math.floor(rnd()*5);   // 가상계좌 입금 대기
    out.push({
      id:'S'+String(101+i),
      region, group: grp,
      date: `2026-${String(d.getMonth()+1).padStart(2,'0')}-${String(d.getDate()).padStart(2,'0')}`,
      time: ['14:00','19:00','10:00'][i%3],
      venue: region.split(' ')[1] ? `${region} 비즈니스센터 ${3+(i%7)}층` : `${region} 컨벤션홀`,
      booked, pending,
      cap: BRAND.capacity,
      round: 1 + (i % 3),
    });
  });
  return out;
}
const SESSIONS = mkSessions();

/* 상태 판정 — 요구사항 2-2 (정원 60명 도달 시 자동 마감) */
function sessState(s){
  const total = s.booked + s.pending;         // ★ 입금 대기분도 좌석을 점유 (제안)
  if (total >= s.cap) return 'closed';
  if (s.cap - total <= 8) return 'hot';
  return 'open';
}
const seatsLeft = s => Math.max(0, s.cap - s.booked - s.pending);

